"""Turn the collected motion recordings into reference motions the human model can perform.

Reads the converted motion collection (the folder holding catalog.json), averages each task's
continuous recording into one loopable cycle (exo_rl/motion_data.py), then checks it twice:
    amplitude   averaging kept >= --min-amplitude of every joint's range of motion
    human model the human (--human, default the MyoLeg muscle model) performs it with the exo off,
                nominal and randomized pilots, whole episodes: no falls / lost tracking, mean
                tracking error < --max-tracking-deg. The recorded ankles are tried first; if the
                human can't perform them, the feet are kept flat instead.
Tasks that pass are written as <out>/<task>.csv; the rest keep their synthetic placeholder
(load_motions falls back per task). <out>/manifest.json records sources, hashes, processing,
every metric and why a task was left out; <out>/README.md carries the attribution.

    python scripts/prepare_motions.py              # collection in data/motion_dataset/ (not in git)
    python scripts/train.py --set human.model=myo --set tasks.data_dir=data/motions/gatech_ab01
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from exo_rl.motion_data import (model_joint_ranges, prepare_cycle, read_angles_csv,  # noqa: E402
                                simulate_task, write_motion_csv)
from exo_rl.utils import load_config  # noqa: E402

# task -> (file in the collection, kind). Georgia Tech 2023 subject AB01 for all tasks, as in
# the collection's catalog coverage; quick_steps is its approved rapid-stepping approximation.
TASKS = {
    "squat": ("gatech_2023/ab01_squat.csv", "squat"),
    "high_knees": ("gatech_2023/ab01_high_knees.csv", "locomotion"),
    "quick_steps": ("candidates/gatech_2023/ab01_tire_run_1.csv", "locomotion"),
    "backward_walk": ("gatech_2023/ab01_backward_walk.csv", "locomotion"),
    "walk": ("gatech_2023/ab01_walk.csv", "locomotion"),
}
PROVENANCE_KEYS = ["dataset", "subject", "motion_protocol", "source_doi", "license", "source_url",
                   "archive_member", "source_sha256", "csv_sha256", "duration_s", "sampling_rate_hz",
                   "column_mapping", "limitations"]


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def catalog_entry(catalog: dict, rel: str) -> dict:
    for rec in catalog.get("recordings", []) + catalog.get("candidates", []):
        if rec.get("csv") == rel:
            return rec
    raise SystemExit(f"{rel} is not in catalog.json")


def readme(manifest: dict) -> str:
    rows = "\n".join(
        f"| `{t}` | {e['status']} | {e['source']['motion_protocol']} | "
        f"{e['cycle']['period_s'] if 'cycle' in e else '-'} | {e.get('ankle', '-')} | {e.get('reason', '')} |"
        for t, e in manifest["tasks"].items())
    human = manifest["checks"]["human_model"]
    return f"""# Recorded reference motions: Georgia Tech 2023, subject AB01

Generated by `scripts/prepare_motions.py`; `manifest.json` has the sources, hashes and every metric.
Checked on the `{human}` human model (`human.model: {human}`). Use with
`--set human.model={human} --set tasks.data_dir=data/motions/gatech_ab01`. Tasks without a CSV here
use their synthetic placeholder.

| task | status | recording | period (s) | ankle | note |
|---|---|---|---|---|---|
{rows}

## What was changed from the recording

- Repeats were cut from the continuous trial, time-normalised and averaged; the period is their
  mean duration. Atypical repeats were dropped (counts in `manifest.json`).
- Low-passed with a truncated Fourier series, so the cycle loops without a jump.
- Hip and knee (the exo's joints) are the recorded averages, softly kept inside the human model's
  joint range (`change_from_recording_deg` in `manifest.json` says by how much; MyoLeg's knee stops
  at 120 deg, so a deeper squat is flattened at the bottom).
- Ankles are the recorded ones when the human model can perform them (ankle = `recorded`);
  otherwise they are replaced by the angle that keeps each foot parallel to the floor, as in the
  synthetic motions (ankle = `flat`).
- The recordings have no pelvis channel. Trunk (root pitch) is 0 deg for locomotion (OpenSim
  pelvis pitch averages within about 1 deg of 0 in Gait120 walking, slopes, stairs and the Hamner
  running example) and, for squats, the pitch that keeps both feet flat (ankle + hip - knee).

## Attribution

Scherpereel K, et al. A human lower-limb biomechanics and wearable sensors dataset during cyclic
and non-cyclic activities. Georgia Tech, 2023. https://doi.org/10.35090/gatech/70296
Licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/); modified as described above.
"""


def check(cfg: dict, task: str, args) -> tuple[dict, list]:
    """Human-model episodes (exo off) for `task` and the problems that block it."""
    val = {"nominal": simulate_task(cfg, task, range(3), nominal=True),
           "randomized": simulate_task(cfg, task, range(100, 100 + args.random_pilots), nominal=False)}
    problems = []
    for k, v in val.items():
        if v["failed"]:
            problems.append(f"{k}: {v['failed']}/{v['episodes']} episodes ended early ({', '.join(v['fail_reasons'])})")
        if v["tracking_rms_deg"] >= args.max_tracking_deg:
            problems.append(f"{k}: tracking error {v['tracking_rms_deg']} deg")
    return val, problems


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", default="data/motion_dataset/recorded", help="collection folder holding catalog.json")
    ap.add_argument("--out", default="data/motions/gatech_ab01")
    ap.add_argument("--human", choices=["myo", "torque"], default="myo",
                    help="human model the motions must work on (human.model)")
    ap.add_argument("--config", default="configs/default.yaml", help="env used for the human-model check")
    ap.add_argument("--set", action="append", default=[], help="config override, e.g. human.muscle.effort=mean")
    ap.add_argument("--tasks", nargs="+", default=list(TASKS), choices=list(TASKS))
    ap.add_argument("--random-pilots", type=int, default=10, help="randomized episodes per task (plus 3 nominal)")
    ap.add_argument("--min-amplitude", type=float, default=0.8)
    ap.add_argument("--max-tracking-deg", type=float, default=8.0, help="same bar as tests/test_sim.py")
    ap.add_argument("--force", action="store_true", help="write tasks that fail a check (marked in the manifest)")
    args = ap.parse_args()

    with open(os.path.join(args.source, "catalog.json")) as f:
        catalog = json.load(f)
    base_cfg = load_config(args.config, [f"human.model={args.human}", *args.set])
    ranges = model_joint_ranges(args.human)
    method = {"cutoff_hz": 8.0, "min_harmonics": 6, "duration_tol": 0.25, "shape_tol": 2.5,
              "soft_limit": "1 deg inside each joint limit, 3 deg margin", "csv_rate_hz": 500.0,
              "ankle": "recorded if the human model performs it, else feet kept flat"}
    manifest = {
        "generated_by": "scripts/prepare_motions.py",
        "collection_date": catalog.get("collection_date"),
        "method": method,
        "checks": {"human_model": args.human, "overrides": args.set,
                   "min_amplitude_retained": args.min_amplitude, "max_tracking_rms_deg": args.max_tracking_deg,
                   "episodes": f"3 nominal + {args.random_pilots} randomized pilots, exo off, whole episodes",
                   "config": args.config},
        "tasks": {},
    }
    os.makedirs(args.out, exist_ok=True)
    synth = {**base_cfg, "tasks": {**base_cfg["tasks"], "data_dir": None}}

    with tempfile.TemporaryDirectory() as staging:
        cfg = {**base_cfg, "tasks": {**base_cfg["tasks"], "data_dir": staging}}
        for task in args.tasks:
            rel, kind = TASKS[task]
            path = os.path.join(args.source, rel)
            rec = catalog_entry(catalog, rel)
            if sha256(path) != rec["csv_sha256"]:
                raise SystemExit(f"{rel}: SHA-256 does not match catalog.json")
            entry = {"source": {"file": rel, **{k: rec[k] for k in PROVENANCE_KEYS if k in rec}}}
            manifest["tasks"][task] = entry
            print(f"{task}: {rel}")
            t, q = read_angles_csv(path)
            csv_path = os.path.join(staging, f"{task}.csv")

            attempts = {}
            for ankle in ("recorded", "flat"):
                cycle = prepare_cycle(t, q, kind, ranges=ranges, foot_flat=ankle == "flat",
                                      cutoff_hz=method["cutoff_hz"], min_harmonics=method["min_harmonics"],
                                      duration_tol=method["duration_tol"], shape_tol=method["shape_tol"])
                amp = min(cycle.info["amplitude_retained"].values())
                if amp < args.min_amplitude:      # same for both ankle choices: no point simulating
                    attempts = {ankle: (cycle, {}, [f"repeats too irregular to average: averaging keeps {amp:.0%} "
                                                    f"of a joint's range of motion (< {args.min_amplitude:.0%})"])}
                    break
                write_motion_csv(csv_path, cycle, method["csv_rate_hz"])
                val, problems = check(cfg, task, args)
                attempts[ankle] = (cycle, val, problems)
                print(f"  ankle {ankle:8s}: tracking {val['nominal']['tracking_rms_deg']}/{val['randomized']['tracking_rms_deg']}"
                      f" deg, failed {val['nominal']['failed']}/3 nominal {val['randomized']['failed']}/{args.random_pilots} randomized")
                if not problems:
                    break
            ankle = next((a for a, (_, _, p) in attempts.items() if not p), next(iter(attempts)))
            cycle, val, problems = attempts[ankle]
            entry.update({"ankle": ankle, "cycle": cycle.info,
                          "validation": {**val, "synthetic_for_comparison": simulate_task(synth, task, range(3), True)}})
            if len(attempts) > 1 or problems:
                entry["ankle_attempts"] = {a: p or "passed" for a, (_, _, p) in attempts.items()}

            out_csv = os.path.join(args.out, f"{task}.csv")
            if problems and not args.force:
                entry["status"] = "not written (synthetic placeholder used)"
                entry["reason"] = "; ".join(problems)
                if os.path.exists(out_csv):
                    os.remove(out_csv)
            else:
                write_motion_csv(out_csv, cycle, method["csv_rate_hz"])
                entry["status"] = "forced despite failed checks" if problems else "ready"
                if problems:
                    entry["reason"] = "; ".join(problems)
            print(f"  {entry['status']} (ankle {ankle}), period {cycle.period:.3f} s, "
                  f"{cycle.info['repeats_used']}/{cycle.info['repeats_found']} repeats")
            for p in problems:
                print(f"  - {p}")

    with open(os.path.join(args.out, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=1)
        f.write("\n")
    with open(os.path.join(args.out, "README.md"), "w") as f:
        f.write(readme(manifest))
    ready = [t for t, e in manifest["tasks"].items() if e["status"] != "not written (synthetic placeholder used)"]
    print(f"\nwrote {len(ready)} task(s) to {args.out}: {', '.join(ready) or 'none'}")
    print(f"use with: --set human.model={args.human} --set tasks.data_dir={args.out}")


if __name__ == "__main__":
    main()
